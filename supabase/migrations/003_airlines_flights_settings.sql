-- ---------------------------------------------------------------------------
-- Reference data: airlines and flights.
--
-- airlines is keyed by IATA code and holds the display name and an optional
-- logo. flights is a cache filled by the flight-lookup Edge Function (using
-- the service role, which bypasses row-level security): one row per
-- airline + flight number with the route, operating carrier and aircraft the
-- provider last reported. Nobody edits flights from the browser; the site
-- only reads it, which is what lets the submit form refuse flights that do
-- not exist.
-- ---------------------------------------------------------------------------
create table if not exists public.airlines (
  iata       text primary key check (iata ~ '^[A-Z0-9]{2}$'),
  icao       text,
  name       text not null,
  logo_url   text,
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.airlines enable row level security;
drop policy if exists airlines_read on public.airlines;
create policy airlines_read on public.airlines for select using (true);
drop policy if exists airlines_admin_write on public.airlines;
create policy airlines_admin_write on public.airlines
  for all using (public.is_admin()) with check (public.is_admin());
grant select on public.airlines to anon, authenticated;
grant insert, update, delete on public.airlines to authenticated;

create table if not exists public.flights (
  id               bigint generated by default as identity primary key,
  airline_iata     text not null references public.airlines(iata),
  number           text not null check (number ~ '^[0-9]{1,4}$'),
  found            boolean not null default true,
  origin_iata      text,
  destination_iata text,
  operating_iata   text references public.airlines(iata),
  codeshare        boolean,
  aircraft         text,
  first_seen       timestamptz not null default now(),
  last_seen        timestamptz not null default now(),
  checked_at       timestamptz not null default now(),
  source           text,
  unique (airline_iata, number)
);
alter table public.flights enable row level security;
drop policy if exists flights_read on public.flights;
create policy flights_read on public.flights for select using (true);
-- no insert/update policy on purpose: only the Edge Function (service role) writes here.
grant select on public.flights to anon, authenticated;

-- Site-wide settings, such as which design is active. Readable by everyone,
-- written only by admins.
create table if not exists public.site_settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;
drop policy if exists site_settings_read on public.site_settings;
create policy site_settings_read on public.site_settings for select using (true);
drop policy if exists site_settings_admin_write on public.site_settings;
create policy site_settings_admin_write on public.site_settings
  for all using (public.is_admin()) with check (public.is_admin());
grant select on public.site_settings to anon, authenticated;
grant insert, update, delete on public.site_settings to authenticated;
insert into public.site_settings (key, value)
  values ('design', '{"skin": "current", "layout": "cards"}'::jsonb)
  on conflict (key) do nothing;

-- Reviews point at the airline and, when validated, the flight. The legacy
-- free-text airline column stays for older rows and for display; a trigger
-- keeps it in step with the airline table when a code is given.
alter table public.reviews add column if not exists airline_iata text references public.airlines(iata);
alter table public.reviews add column if not exists flight_id bigint references public.flights(id) on delete set null;
create index if not exists reviews_airline_iata_idx on public.reviews (airline_iata);
create index if not exists reviews_flight_idx on public.reviews (flight_id);

create or replace function public.fill_airline_name()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.airline_iata is not null then
    new.airline := coalesce((select name from public.airlines where iata = new.airline_iata), new.airline);
  end if;
  return new;
end;
$$;
drop trigger if exists reviews_fill_airline_name on public.reviews;
create trigger reviews_fill_airline_name
  before insert or update on public.reviews
  for each row execute function public.fill_airline_name();

