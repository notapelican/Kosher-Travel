drop view if exists public.reviews_public;
create view public.reviews_public as
  select r.id,
         case when r.is_anonymous then null else r.user_id end as user_id,
         r.airline, r.airline_iata, r.flight_number, r.flight_id,
         r.origin_city, r.destination_city, r.flight_date,
         r.cabin_class, r.meal_type, r.meal_name, r.hechsher, r.rating, r.comment, r.photos,
         r.respect_score, r.kosher_care_score, r.experience_notes,
         r.author_name, r.is_anonymous, r.created_at,
         f.origin_iata, f.destination_iata, f.operating_iata, f.codeshare, f.aircraft,
         a.name as airline_name, a.logo_url as airline_logo_url
  from public.reviews r
  left join public.flights f on f.id = r.flight_id
  left join public.airlines a on a.iata = r.airline_iata
  where not r.is_hidden;

grant select on public.reviews_public to anon, authenticated;

-- Table privileges for the API roles. Supabase normally sets these as default
-- privileges when a project has "Automatically expose new tables" switched on;
-- granting them here makes the schema work either way. Signed-out visitors
-- only ever read the reviews_public view above; signed-in users reach the
-- tables, and row-level security decides which rows.
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.profiles to authenticated;
grant select, insert, update, delete on public.reviews to authenticated;
grant usage, select on sequence public.reviews_id_seq to authenticated;

-- ---------------------------------------------------------------------------
-- Storage bucket for meal photos: public read, owner-scoped write.
-- Photos are stored at  meal-photos/<user id>/<random>.jpg
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('meal-photos', 'meal-photos', true, 5242880,
        array['image/jpeg','image/png','image/webp','image/heic'])
on conflict (id) do update
  set public = true,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists meal_photos_read on storage.objects;
create policy meal_photos_read on storage.objects
  for select using (bucket_id = 'meal-photos');

drop policy if exists meal_photos_insert on storage.objects;
create policy meal_photos_insert on storage.objects
  for insert to authenticated with check (
    bucket_id = 'meal-photos'
    and (storage.foldername(name))[1] = auth.uid()::text
    and not public.is_banned()
  );

drop policy if exists meal_photos_delete on storage.objects;
create policy meal_photos_delete on storage.objects
  for delete to authenticated using (
    bucket_id = 'meal-photos'
    and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
  );
