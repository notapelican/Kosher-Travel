-- ---------------------------------------------------------------------------
-- profiles: one row per signed-in user, created automatically on signup.
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id           uuid primary key references auth.users on delete cascade,
  email        text,
  display_name text,
  is_admin     boolean not null default false,
  is_banned    boolean not null default false,
  created_at   timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(
      new.raw_user_meta_data->>'full_name',
      new.raw_user_meta_data->>'name',
      split_part(coalesce(new.email, 'traveler'), '@', 1)
    )
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Helper used by policies. security definer so it can read profiles without
-- re-entering the policies that call it.
create or replace function public.is_admin()
returns boolean
language sql
security definer set search_path = public
stable
as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

create or replace function public.is_banned()
returns boolean
language sql
security definer set search_path = public
stable
as $$
  select coalesce((select is_banned from public.profiles where id = auth.uid()), false);
$$;

-- ---------------------------------------------------------------------------
-- reviews: one row per rated meal.
-- ---------------------------------------------------------------------------
create table if not exists public.reviews (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references public.profiles(id) on delete cascade,
  airline        text not null,
  flight_number  text,
  origin_city    text not null,
  destination_city text,
  flight_date    date,
  cabin_class    text,
  meal_type      text,
  meal_name      text,
  hechsher       text,
  rating         smallint not null check (rating between 1 and 5),
  comment        text,
  photos         text[] not null default '{}',

  -- How the airline treats Jewish travelers. Both are optional: a reviewer
  -- who has nothing to say leaves them blank rather than guessing.
  respect_score     smallint check (respect_score is null or respect_score between 1 and 5),
  kosher_care_score smallint check (kosher_care_score is null or kosher_care_score between 1 and 5),
  experience_notes  text,

  -- A reviewer may post under their display name or anonymously, per review.
  is_anonymous   boolean not null default false,
  author_name    text not null default 'Traveler',
  is_hidden      boolean not null default false,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index if not exists reviews_created_at_idx on public.reviews (created_at desc);
create index if not exists reviews_airline_idx on public.reviews (lower(airline));
create index if not exists reviews_origin_idx on public.reviews (lower(origin_city));
create index if not exists reviews_hechsher_idx on public.reviews (lower(hechsher));
create index if not exists reviews_user_idx on public.reviews (user_id);
create index if not exists reviews_respect_idx on public.reviews (respect_score);
create index if not exists reviews_kosher_care_idx on public.reviews (kosher_care_score);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists reviews_touch_updated_at on public.reviews;
create trigger reviews_touch_updated_at
  before update on public.reviews
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.reviews  enable row level security;

-- profiles: you can read and edit your own; admins can read and edit everyone.
drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles
  for select using (id = auth.uid() or public.is_admin());

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
  for update using (id = auth.uid())
  -- a normal user may rename themselves but not grant themselves powers
  with check (
    id = auth.uid()
    and is_admin  = public.is_admin()
    and is_banned = public.is_banned()
  );

drop policy if exists profiles_admin_all on public.profiles;
create policy profiles_admin_all on public.profiles
  for all using (public.is_admin()) with check (public.is_admin());

-- reviews: the table itself is readable only by the row's owner and by admins.
-- Everyone else browses through the reviews_public view defined below, which
-- withholds the poster's id on anonymous reviews.
drop policy if exists reviews_select_own_or_admin on public.reviews;
create policy reviews_select_own_or_admin on public.reviews
  for select using (user_id = auth.uid() or public.is_admin());

-- any signed-in, non-banned user may post; no per-meal limit.
drop policy if exists reviews_insert_own on public.reviews;
create policy reviews_insert_own on public.reviews
  for insert with check (
    user_id = auth.uid()
    and not public.is_banned()
    and not is_hidden
  );

drop policy if exists reviews_update_own on public.reviews;
create policy reviews_update_own on public.reviews
  for update using (user_id = auth.uid() and not public.is_banned())
  with check (user_id = auth.uid());

drop policy if exists reviews_delete_own on public.reviews;
create policy reviews_delete_own on public.reviews
  for delete using (user_id = auth.uid());

drop policy if exists reviews_admin_all on public.reviews;
create policy reviews_admin_all on public.reviews
  for all using (public.is_admin()) with check (public.is_admin());

-- ---------------------------------------------------------------------------
-- author_name is copied onto each review so the site can render bylines
-- without ever reading the profiles table (which holds email addresses).
-- ---------------------------------------------------------------------------
create or replace function public.set_review_author_name()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  new.author_name := case
    when new.is_anonymous then 'Anonymous'
    else coalesce(
      nullif(trim((select display_name from public.profiles where id = new.user_id)), ''),
      'Traveler')
  end;
  return new;
end;
$$;

drop trigger if exists reviews_set_author_name on public.reviews;
create trigger reviews_set_author_name
  before insert or update on public.reviews
  for each row execute function public.set_review_author_name();

-- Recomputed on update too, so nobody can post under someone else's name.

-- Renaming yourself updates the byline on everything you have posted.
create or replace function public.sync_author_name()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.display_name is distinct from old.display_name then
    update public.reviews
       set author_name = coalesce(nullif(trim(new.display_name), ''), 'Traveler')
     where user_id = new.id
       and not is_anonymous;
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_sync_author_name on public.profiles;
create trigger profiles_sync_author_name
  after update on public.profiles
  for each row execute function public.sync_author_name();

-- ---------------------------------------------------------------------------
-- reviews_public: what signed-out visitors and the browse page read.
--
-- security_invoker is deliberately left off, so the view runs as its owner and
-- bypasses the table policy above — that is what lets anyone browse. It does
-- its own filtering instead: hidden reviews never appear, and an anonymous
-- review's user_id is nulled out so nobody can tie a person's anonymous posts
-- to their named ones.
-- ---------------------------------------------------------------------------
-- ---------------------------------------------------------------------------
-- Reference data: airlines and flights.
--
-- airlines is keyed by IATA code and holds the display name and an optional
-- logo. flights is a cache filled by the flight-lookup Edge Function (using
-- the service role, which bypasses row-level security): one row per
-- airline + flight number with the route, operating carrier and aircraft the
-- provider last reported. Nobody edits flights from the browser; the site
-- only reads it, which is what lets the submit form refuse flights that do
-- not exist.
-- ---------------------------------------------------------------------------
create table if not exists public.airlines (
  iata       text primary key check (iata ~ '^[A-Z0-9]{2}$'),
  icao       text,
  name       text not null,
  logo_url   text,
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.airlines enable row level security;
drop policy if exists airlines_read on public.airlines;
create policy airlines_read on public.airlines for select using (true);
drop policy if exists airlines_admin_write on public.airlines;
create policy airlines_admin_write on public.airlines
  for all using (public.is_admin()) with check (public.is_admin());
grant select on public.airlines to anon, authenticated;
grant insert, update, delete on public.airlines to authenticated;

create table if not exists public.flights (
  id               bigint generated by default as identity primary key,
  airline_iata     text not null references public.airlines(iata),
  number           text not null check (number ~ '^[0-9]{1,4}$'),
  found            boolean not null default true,
  origin_iata      text,
  destination_iata text,
  operating_iata   text references public.airlines(iata),
  codeshare        boolean,
  aircraft         text,
  first_seen       timestamptz not null default now(),
  last_seen        timestamptz not null default now(),
  checked_at       timestamptz not null default now(),
  source           text,
  unique (airline_iata, number)
);
alter table public.flights enable row level security;
drop policy if exists flights_read on public.flights;
create policy flights_read on public.flights for select using (true);
-- no insert/update policy on purpose: only the Edge Function (service role) writes here.
grant select on public.flights to anon, authenticated;

