-- ---------------------------------------------------------------------------
-- Meals. A report is one flight; each meal served on it is a review_meals row.
-- ---------------------------------------------------------------------------
alter table public.reviews alter column rating drop not null;

create table if not exists public.review_meals (
  id         bigint generated by default as identity primary key,
  review_id  bigint not null references public.reviews(id) on delete cascade,
  position   smallint not null check (position between 1 and 6),
  meal_type  text,
  meal_name  text,
  hechsher   text,
  rating     smallint not null check (rating between 1 and 5),
  comment    text,
  photos     text[] not null default '{}' check (cardinality(photos) <= 4),
  created_at timestamptz not null default now(),
  unique (review_id, position)
);
create index if not exists review_meals_review_idx on public.review_meals (review_id);
create index if not exists review_meals_hechsher_idx on public.review_meals (hechsher);

alter table public.review_meals enable row level security;

-- A meal belongs to whoever owns its report. Signed-out visitors read meals
-- only through reviews_public, never the table.
drop policy if exists review_meals_select on public.review_meals;
create policy review_meals_select on public.review_meals
  for select using (
    exists (select 1 from public.reviews r where r.id = review_id
            and (r.user_id = auth.uid() or public.is_admin())));

drop policy if exists review_meals_write_own on public.review_meals;
create policy review_meals_write_own on public.review_meals
  for all using (
    exists (select 1 from public.reviews r where r.id = review_id and r.user_id = auth.uid())
    and not public.is_banned())
  with check (
    exists (select 1 from public.reviews r where r.id = review_id and r.user_id = auth.uid())
    and not public.is_banned());

drop policy if exists review_meals_admin_all on public.review_meals;
create policy review_meals_admin_all on public.review_meals
